#!/bin/bash
set -euo pipefail
root=$(cd "$(dirname "$0")/../ios/SSHProof" && pwd)
sshd_bin=$(command -v sshd || true)
if ! command -v swift >/dev/null || [[ -z "$sshd_bin" ]] || ! command -v ssh-keygen >/dev/null || ! command -v python3 >/dev/null; then
  echo "BLOCKED: swift, sshd, ssh-keygen, and python3 are required" >&2
  exit 2
fi
fixture=$(mktemp -d "${TMPDIR:-/tmp}/sshproof.XXXXXX")
pid=""; pid2=""
cleanup() {
  for running in "$pid" "$pid2"; do
    if [[ -n "$running" ]] && kill -0 "$running" 2>/dev/null; then
      kill "$running" 2>/dev/null || true
      for _ in {1..50}; do kill -0 "$running" 2>/dev/null || break; sleep 0.1; done
      kill -9 "$running" 2>/dev/null || true
      wait "$running" 2>/dev/null || true
    fi
  done
  rm -rf "$fixture"
}
trap cleanup EXIT INT TERM
chmod 700 "$fixture"
mkdir "$fixture/home"
chmod 700 "$fixture/home"
ssh-keygen -q -t ed25519 -N '' -f "$fixture/host_ed25519_key" >/dev/null
# The client key is generated by the same Crypto/NIOSSH code under test, not ssh-keygen.
python3 - "$root" "$fixture/keygen.out" "$fixture/keygen.log" <<'PY'
import subprocess, sys
with open(sys.argv[2], "wb") as output, open(sys.argv[3], "wb") as error:
    try:
        result = subprocess.run(["swift", "run", "-c", "debug", "SSHProofKeygen"], cwd=sys.argv[1], stdout=output, stderr=error, timeout=120)
    except subprocess.TimeoutExpired:
        print("FAILED: SSH proof key generator exceeded its 120 second wall-clock bound", file=sys.stderr)
        raise SystemExit(124)
raise SystemExit(result.returncode)
PY
{ IFS= read -r client_private; IFS= read -r client_public; } < "$fixture/keygen.out"
if [[ -z "${client_private:-}" || -z "${client_public:-}" ]]; then echo "FAILED: key generator did not emit a private value and public key" >&2; tail -n 100 "$fixture/keygen.log" >&2; exit 1; fi
printf '%s\n' "$client_public" > "$fixture/authorized_keys"
chmod 600 "$fixture/authorized_keys"
port=$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()')
cat > "$fixture/sshd_config" <<EOF
HostKey $fixture/host_ed25519_key
AuthorizedKeysFile $fixture/authorized_keys
PidFile $fixture/sshd.pid
Port $port
ListenAddress 127.0.0.1
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
UsePAM no
PermitRootLogin no
StrictModes no
AllowUsers $(id -un)
AllowAgentForwarding no
AllowTcpForwarding no
X11Forwarding no
PermitTunnel no
GatewayPorts no
LogLevel VERBOSE
EOF
"$sshd_bin" -t -f "$fixture/sshd_config"
HOME="$fixture/home" "$sshd_bin" -D -e -f "$fixture/sshd_config" >"$fixture/sshd.log" 2>&1 & pid=$!
for _ in {1..50}; do grep -q 'Server listening' "$fixture/sshd.log" && break; sleep 0.1; done
if ! grep -q 'Server listening' "$fixture/sshd.log"; then
  echo "FAILED: isolated sshd did not bind loopback" >&2; tail -n 100 "$fixture/sshd.log" >&2; exit 1
fi
no_tty_port=$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()')
cat > "$fixture/sshd_no_tty_config" <<EOF
HostKey $fixture/host_ed25519_key
AuthorizedKeysFile $fixture/authorized_keys
PidFile $fixture/sshd-no-tty.pid
Port $no_tty_port
ListenAddress 127.0.0.1
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
UsePAM no
PermitRootLogin no
StrictModes no
AllowUsers $(id -un)
PermitTTY no
AllowAgentForwarding no
AllowTcpForwarding no
X11Forwarding no
PermitTunnel no
GatewayPorts no
LogLevel VERBOSE
EOF
"$sshd_bin" -t -f "$fixture/sshd_no_tty_config"
HOME="$fixture/home" "$sshd_bin" -D -e -f "$fixture/sshd_no_tty_config" >"$fixture/sshd-no-tty.log" 2>&1 & pid2=$!
for _ in {1..50}; do grep -q 'Server listening' "$fixture/sshd-no-tty.log" && break; sleep 0.1; done
if ! grep -q 'Server listening' "$fixture/sshd-no-tty.log"; then tail -n 100 "$fixture/sshd-no-tty.log" >&2; exit 1; fi
host_key="$fixture/host_ed25519_key.pub"
marker="$fixture/pty-rejection-exec-marker"
export SSH_PROOF_PORT="$port" SSH_PROOF_NO_TTY_PORT="$no_tty_port" SSH_PROOF_NO_TTY_MARKER="$marker"
export SSH_PROOF_USER="$(id -un)" SSH_PROOF_HOST_KEY="$host_key" SSH_PROOF_CLIENT_PRIVATE_KEY="$client_private"
if ! python3 - "$root" "$fixture/swift-test.log" <<'PY'
import os, subprocess, sys
with open(sys.argv[2], "wb") as log:
    try:
        result = subprocess.run(["swift", "test"], cwd=sys.argv[1], env=os.environ, stdout=log, stderr=subprocess.STDOUT, timeout=90)
    except subprocess.TimeoutExpired:
        print("FAILED: SSH proof tests exceeded their 90 second wall-clock bound", file=sys.stderr)
        raise SystemExit(124)
raise SystemExit(result.returncode)
PY
then
  tail -n 200 "$fixture/swift-test.log" >&2; exit 1
fi
accepted=$(grep -c 'Accepted publickey' "$fixture/sshd.log" || true)
if [[ "$accepted" != 5 ]]; then
  echo "FAILED: expected exactly 5 successful public-key authentications (saw $accepted)" >&2
  tail -n 200 "$fixture/sshd.log" >&2; exit 1
fi
no_tty_accepted=$(grep -c 'Accepted publickey' "$fixture/sshd-no-tty.log" || true)
if [[ "$no_tty_accepted" != 1 || -e "$marker" ]]; then
  echo "FAILED: PermitTTY fixture did not reject before exec" >&2; tail -n 100 "$fixture/sshd-no-tty.log" >&2; exit 1
fi
echo "PASS: isolated OpenSSH proof: distinct unknown/changed/wrong-auth/PTY errors, trust-before-auth, PTY/input/resize/status/empty-EOF, output cap, bounded resolver/TCP timeout, cancellation, and reverse completion ordering"
